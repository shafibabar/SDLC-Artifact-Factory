#!/bin/bash
# Synthetic-input test for mock-generation's validate-test-doubles.sh.
set -uo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
V="$SCRIPT_DIR/../../skills/mock-generation/scripts/validate-test-doubles.sh"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
FAILED=0

# expect <name> <exit-code> <output-regex> <args...>
expect() {
  local name="$1" code="$2" pattern="$3"; shift 3
  local out rc
  out="$(bash "$V" "$@" 2>&1)"; rc=$?
  if [ "$rc" -eq "$code" ] && grep -qE "$pattern" <<<"$out"; then
    echo "PASS: $name"
  else
    echo "FAIL: $name (exit $rc, want $code /$pattern/)"; echo "$out"; FAILED=1
  fi
}
# bad <name> <relative file> <rule> <content>
bad() {
  mkdir -p "$(dirname "$TMP/bad/$1/$2")"
  printf '%s\n' "$4" > "$TMP/bad/$1/$2"
  expect "$1" 1 "FAIL $3 " "$TMP/bad/$1"
}
MARK='// Code generated by moq; DO NOT EDIT.'
DIRECTIVE='//go:generate go run github.com/matryer/moq@v0.8.1 -out sender_moq.go . Sender'

bad gomock a_test.go M5 'import "go.uber.org/mock/gomock"'
bad testify-mock a_test.go M5 'import "github.com/stretchr/testify/mock"'
bad mockgen ports.go M5 '//go:generate mockgen -destination=mocks/x.go . Sender'
bad mockery-config .mockery.yaml M5 'all: false'
bad makefile-mockery Makefile M5 '	mockery --all'
bad latest Makefile M5 '	go install github.com/matryer/moq@latest'
bad orphan sender_moq.go M5 "$MARK"
bad wrong-name sender_mock.go M5 "$MARK"
bad repo-calls a_test.go M2 '	require.Len(t, repo.SaveCalls(), 1)'
bad repo-calls-named a_test.go M2 '	require.Len(t, orderRepository.SaveCalls(), 1)'
bad py-repo-assert test_a.py M2 'fake_repo.save.assert_called_once_with(order)'
bad py-repo-count test_a.py M2 'assert repository.save.call_count == 1'
bad no-assertion internal/test/fakes/repo.go FAKE 'type OrderRepo struct{}'
bad fake-by-name a_test.go FAKE 'type fakeRepo struct{}'
bad fake-header internal/test/fakes/repo.go M6 "$MARK
type OrderRepo struct{}
var _ Port = (*OrderRepo)(nil)"

mkdir -p "$TMP/bad/no-marker"
printf '%s\n' "$DIRECTIVE" > "$TMP/bad/no-marker/ports.go"
printf 'package app\n' > "$TMP/bad/no-marker/sender_moq.go"
expect "moq file without marker" 1 "FAIL M6 " "$TMP/bad/no-marker"

mkdir -p "$TMP/good/app" "$TMP/good/internal/test/fakes" "$TMP/good/vendor/x"
printf '%s\n' "$DIRECTIVE" > "$TMP/good/app/ports.go"
printf '%s\npackage app\ntype SenderMock struct{}\n' "$MARK" > "$TMP/good/app/sender_moq.go"
cat > "$TMP/good/internal/test/fakes/repo.go" <<'GO'
package fakes

// repo.SaveCalls() in a comment is ignored
type OrderRepo struct{}

var (
	_ application.OrderRepository = (*OrderRepo)(nil)
)
GO
cat > "$TMP/good/app/a_test.go" <<'GO'
require.Len(t, sender.SendCalls(), 1)
require.Len(t, reporter.SendCalls(), 1)
GO
printf 'import "go.uber.org/mock/gomock"\n' > "$TMP/good/vendor/x/v.go"
printf 'publisher.publish.assert_called_once_with(event)\n' > "$TMP/good/test_ok.py"
expect "clean tree passes, vendor skipped" 0 "0 FAIL, 0 WARN" "$TMP/good"

mkdir -p "$TMP/warn"
cat > "$TMP/warn/ports.go" <<'GO'
//go:generate moq -stub -skip-ensure -out sender_moq.go . Sender
GO
expect "stub and skip-ensure warn only" 0 "0 FAIL, 2 WARN" "$TMP/warn"
printf '//go:generate moq -out pool_moq.go github.com/jackc/pgx/v5 Tx\n' > "$TMP/warn/ports.go"
expect "library port warns" 0 "WARN M1 " "$TMP/warn"

mkdir -p "$TMP/empty"
expect "no arguments" 2 "usage"
expect "missing path" 2 "no such path" "$TMP/nope"
expect "empty directory" 2 "nothing was checked" "$TMP/empty"

[ "$FAILED" -eq 0 ] && echo "ALL PASS: validate-test-doubles" || exit 1
