#!/bin/bash
# Synthetic-input test for python-unit-test's check-python-coverage.sh.
# The first part needs only python3: a stub interpreter stands in for pytest and
# writes hand-made reports. The second part runs real pytest and pytest-cov, and
# is skipped with a message when they are absent (point PYTHON_WITH_PYTEST at an
# interpreter that has pytest, pytest-asyncio and pytest-cov to run it).
set -uo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
S="$SCRIPT_DIR/../../skills/python-unit-test/scripts/check-python-coverage.sh"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
export PYTHONDONTWRITEBYTECODE=1
FAILED=0

# expect <name> <exit-code> <output-regex> <args...>
expect() {
  local name="$1" code="$2" pattern="$3"; shift 3
  local out rc
  out="$(bash "$S" "$@" 2>&1)"; rc=$?
  if [ "$rc" -eq "$code" ] && grep -qE -- "$pattern" <<<"$out"; then
    echo "PASS: $name"
  else
    echo "FAIL: $name (exit $rc, want $code /$pattern/)"; echo "$out"; FAILED=1
  fi
}

M="$TMP/proj"; mkdir -p "$M/src/p" "$M/tests"
printf 'def a(x):\n    return x\n' > "$M/src/p/a.py"

# Stub interpreter: copies $STUB_REPORT and a JUnit file to the requested paths.
cat > "$TMP/stub" <<'STUB'
#!/bin/bash
printf '%s\n' "$@" > "$STUB_LOG"
env | grep -c '^PYTEST_ADDOPTS=' > "$STUB_LOG.env"
for a in "$@"; do case "$a" in
  --cov-report=json:*) [ -n "${STUB_REPORT:-}" ] && cp "$STUB_REPORT" "${a#--cov-report=json:}";;
  --junitxml=*) printf '<testsuites><testsuite tests="%s" skipped="%s"/></testsuites>' "${STUB_TESTS:-3}" "${STUB_SKIPPED:-0}" > "${a#--junitxml=}";;
  --cov-config=*) cp "${a#--cov-config=}" "$STUB_LOG.rc";;
esac; done
echo "${STUB_OUTPUT:-3 passed}"
exit "${STUB_EXIT:-0}"
STUB
chmod +x "$TMP/stub"
export STUB_LOG="$TMP/log"

# report <name> <statements> <missing> <branches> <missing-branches> [excluded-lines] [branch-flag]
report() {
  python3 -I - "$TMP/$1.json" "$2" "$3" "$4" "$5" "${6:-}" "${7:-true}" <<'PY'
import json, sys
path, n, m, b, mb, excluded, flag = sys.argv[1:]
n, m, b, mb = map(int, (n, m, b, mb))
entry = {"summary": {"num_statements": n, "missing_lines": m, "num_branches": b, "missing_branches": mb},
         "missing_lines": list(range(1, m + 1)), "missing_branches": [[1, 2]] * mb,
         "excluded_lines": [int(x) for x in excluded.split(",") if x]}
json.dump({"meta": {"branch_coverage": flag == "true"}, "files": {"src/p/a.py": entry}}, open(path, "w"))
PY
  echo "$TMP/$1.json"
}
run() { expect "$1" "$2" "$3" --python "$TMP/stub" "${@:4}" "$M"; }

export STUB_REPORT; STUB_REPORT="$(report full 4 0 2 0)"
run "complete run passes" 0 "PASS: every measured line and branch ran"
run "counts are printed" 0 "Branch coverage: 2/2"
PYTEST_ADDOPTS="-k x" run "PYTEST_ADDOPTS is cleared" 0 "PASS"
if [ "$(cat "$STUB_LOG.env")" = 0 ] && grep -qx 'addopts=' "$STUB_LOG" && grep -qx -- '--cov-branch' "$STUB_LOG" \
   && grep -q '^branch = True' "$STUB_LOG.rc"; then
  echo "PASS: runs with addopts cleared, branch on and its own config"
else echo "FAIL: pytest command or config"; FAILED=1; fi
STUB_REPORT="$(report line 2503 1 2 0)"; run "one line in 2503 fails" 1 "FAIL \(line\).*Above 90%"
STUB_REPORT="$(report br 10 0 10 1)"; run "exactly 90 branch has no waiver" 1 "FAIL \(branch\).*no waiver"
STUB_REPORT="$(report br91 10 0 11 1)"; run "above 90 branch is waivable" 1 "FAIL \(branch\).*may waive"
STUB_REPORT="$(report nob 4 0 2 0 "" false)"; run "no branch data" 2 "no branch data"
STUB_REPORT="$(report zero 0 0 0 0)"; run "zero statements" 2 "no statements"
STUB_REPORT="$(report exc 4 0 2 0 "1,2")"; run "unapproved excluded lines" 2 "unapproved exclusion: src/p/a.py lines 1, 2"
FP="$(bash "$S" --python "$TMP/stub" "$M" 2>&1 | grep -oE 'lines [0-9a-f]{12}' | head -1)"
printf 'src/p/a.py | %s | approved 2026-01-02 | boot code\n' "$FP" > "$M/excl"
run "approved lines pass" 0 "approved lines 1, 2" --exclusions "$M/excl"
printf 'def a(y):\n    return y\n' > "$M/src/p/a.py"
run "approval lapses when the lines change" 2 "unapproved exclusion" --exclusions "$M/excl"
STUB_REPORT="$(report full 4 0 2 0)"
printf 'src/p/a.py | file | pending | x\n' > "$M/bad"; run "pending entry refused" 2 "not approved" --exclusions "$M/bad"
printf 'src/p/a.py | file | approved 2026-13-40 | x\n' > "$M/bad"; run "bad date refused" 2 "not approved" --exclusions "$M/bad"
printf 'src/p/a.py | file | approved 2026-01-02 |\n' > "$M/bad"; run "reason required" 2 "not approved" --exclusions "$M/bad"
printf 'def b():\n    return 1\n' > "$M/src/p/b.py"; run "file missing from report" 2 "did not measure: src/p/b.py"
printf 'src/p/b.py | file | approved 2026-01-02 | start-up\n' > "$M/excl"
run "approved file is named in the pass" 0 "NOT measured, by approved exception: src/p/b.py" --exclusions "$M/excl"
printf '# Code generated by tool. DO NOT EDIT.\ndef b():\n    return 1\n' > "$M/src/p/b.py"; run "generated marker" 0 "excluded src/p/b.py: generated-code marker"
printf 'def b():\n    return 1\n\n# Code generated by hand. DO NOT EDIT.\n' > "$M/src/p/b.py"; run "late marker ignored" 2 "did not measure"
rm "$M/src/p/b.py"
STUB_OUTPUT="2 passed, 1 deselected in 0.1s" run "deselected tests" 2 "1 test\(s\) deselected"
STUB_EXIT=1 run "failed tests" 2 "pytest exited 1"
STUB_EXIT=5 run "no tests collected" 2 "no tests"
STUB_TESTS=2 STUB_SKIPPED=2 run "everything skipped" 2 "no test ran"
STUB_SKIPPED=1 run "skips are counted" 0 "2 ran, 1 skipped"
STUB_REPORT="" run "missing report" 2 "missing or unreadable report"
run "unit folder cannot be skipped" 2 "accepts only" --skip-suite unit
run "e2e may be skipped" 0 "suites not run: e2e" --skip-suite e2e
run "test selection refused" 2 "unknown argument" -k x
run "source outside project" 2 "inside the project" --source ..
expect "no tests folder" 2 "no tests folder" "$TMP"

REAL="${PYTHON_WITH_PYTEST:-python3}"
if ! "$REAL" -c 'import pytest, pytest_asyncio, pytest_cov' >/dev/null 2>&1; then
  echo "SKIP: real-run cases ($REAL lacks pytest, pytest-asyncio or pytest-cov)"
else
  R="$TMP/real"; mkdir -p "$R/src/p" "$R/tests"; : > "$R/src/p/__init__.py"
  printf '[tool.pytest.ini_options]\npythonpath = ["src"]\naddopts = "-k nothing"\n[tool.coverage.run]\nomit = ["*/a.py"]\n' > "$R/pyproject.toml"
  printf 'def a(x: int) -> int:\n    if x:\n        x += 1\n    return x\n' > "$R/src/p/a.py"
  printf 'from p.a import a\n\n\ndef test_a() -> None:\n    assert a(1) == 2\n' > "$R/tests/test_a.py"
  expect "real: uncovered branch fails despite omit and addopts" 1 "Branch coverage: 1/2" --python "$REAL" "$R"
  printf '\n\ndef test_zero() -> None:\n    assert a(0) == 0\n' >> "$R/tests/test_a.py"
  expect "real: full run passes" 0 "Branch coverage: 2/2" --python "$REAL" "$R"
  printf '\n\ndef hidden() -> int:  # pragma: no cover\n    return 1\n' >> "$R/src/p/a.py"
  expect "real: pragma blocks" 2 "unapproved exclusion" --python "$REAL" "$R"
  mkdir "$R/src/bare"; printf 'def z() -> int:\n    return 1\n' > "$R/src/bare/z.py"
  printf 'def a(x: int) -> int:\n    if x:\n        x += 1\n    return x\n' > "$R/src/p/a.py"
  expect "real: unimported folder is counted" 1 "src/bare/z.py: line" --python "$REAL" "$R"
fi
exit "$FAILED"
