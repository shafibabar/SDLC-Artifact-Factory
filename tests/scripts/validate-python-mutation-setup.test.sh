#!/bin/bash
# Synthetic-input test for python-mutation-test's setup validator: a clean product
# passes, and each defect found in python-mutation-test 1.2.1, or forbidden by the
# product owner's mutation decisions (D048, 2026-11-28), is flagged.
# Needs no mutmut.
set -uo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "$SCRIPT_DIR/../lib/harness.sh"
SCRIPT="$REPO_ROOT/skills/python-mutation-test/scripts/validate-python-mutation-setup.sh"
TMP="$(cd "$(mktemp -d)" && pwd -P)"
trap 'rm -rf "$TMP"' EXIT
FAILURES=0

python3 -I - "$TMP/clean" <<'PY'
import os, sys
root = sys.argv[1]
def put(path, text):
    full = os.path.join(root, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    open(full, "w").write(text)
put("pyproject.toml", """[project]
name = "kilnworks"
version = "0.1.0"

[dependency-groups]
dev = ["pytest==9.2.0", "pytest-cov==7.1.0", "mutmut==3.8.1"]

[tool.pytest.ini_options]
testpaths = ["tests"]
strict = true

[tool.mutmut]
source_paths = ["src/kilnworks"]
pytest_add_cli_args = ["--no-cov"]
do_not_mutate = ["src/kilnworks/adapters/kiln_api.py"]
""")
put("uv.lock", 'version = 1\n\n[[package]]\nname = "mutmut"\nversion = "3.8.1"\nsource = { registry = "https://pypi.org/simple" }\n')
put(".gitignore", "mutants/\nmutation-out/\n")
put("src/kilnworks/__init__.py", "")
put("src/kilnworks/domain/firing.py", "def next_slot(a: int) -> int:\n    return a + 1\n")
put("src/kilnworks/adapters/kiln_api.py", "# Code generated by openapi-python-client. DO NOT EDIT.\ndef url(p: str) -> str:\n    return '/' + p\n")
put("tests/fakes.py", "class FakeKiln:\n    def fire(self) -> None:\n        pass\n")
put("scripts/run-python-mutation.sh", "#!/bin/bash\n")
put("scripts/check-python-mutation.sh", "#!/bin/bash\n")
put("mutation/mutant-record.txt", "# record\nkilnworks.domain.firing.x_next_slot__mutmut_2 | equivalent | 0123456789ab | "
    "no caller can observe the difference at this boundary | test-strategist 2026-11-28\n")
put("mutation/exclusions.txt", "# exclusions\n")
put("Makefile", """MUTMUT_VERSION := 3.8.1

mutation:
\tuv run --frozen bash scripts/run-python-mutation.sh --mutmut-version $(MUTMUT_VERSION) .
\tuv run --frozen bash scripts/check-python-mutation.sh --mode release --commit "$$(git rev-parse HEAD)" --record mutation/mutant-record.txt .

mutation-changed:
\tuv run --frozen bash scripts/run-python-mutation.sh --changed-since "$$(git describe --tags --abbrev=0)" .
\tuv run --frozen bash scripts/check-python-mutation.sh --mode scheduled --commit "$$(git rev-parse HEAD)" .
""")
put(".github/workflows/mutation.yml", """name: mutation
on:
  schedule:
    - cron: "41 3 1 * *"
  workflow_dispatch:
  workflow_call:
    inputs:
      scope:
        type: string
        default: full
jobs:
  mutation:
    runs-on: ubuntu-26.04
    steps:
      - uses: actions/checkout@v7
        with:
          fetch-depth: 0
      - run: make install
      - if: ${{ inputs.scope == 'full' }}
        run: make mutation
      - if: ${{ inputs.scope != 'full' }}
        run: make mutation-changed
""")
put(".github/workflows/release.yml", """name: release
on:
  push:
    tags: ["v*"]
jobs:
  mutation:
    uses: ./.github/workflows/mutation.yml
    with:
      scope: full
  publish:
    needs: [mutation]
    runs-on: ubuntu-26.04
    steps:
      - run: echo publish
""")
PY

# case_ <name> <expected exit> <regex> <python that edits files under root via put/sub/drop>
case_() {
  local name="$1" want="$2" pattern="$3" change="$4"
  rm -rf "$TMP/p"; cp -R "$TMP/clean" "$TMP/p"
  python3 -I - "$TMP/p" "$change" <<'PY'
import os, sys
root, change = sys.argv[1], sys.argv[2]
def put(path, text):
    full = os.path.join(root, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    open(full, "w").write(text)
def sub(path, old, new):
    text = open(os.path.join(root, path)).read()
    assert old in text, (path, old)
    open(os.path.join(root, path), "w").write(text.replace(old, new))
def drop(path):
    os.remove(os.path.join(root, path))
exec(change)
PY
  local out code
  out="$(/bin/bash "$SCRIPT" "$TMP/p" 2>&1)"; code=$?
  if [ "$code" -eq "$want" ] && grep -E -- "$pattern" > /dev/null <<<"$out"; then
    echo "PASS: $name"
  else
    echo "FAIL: $name (exit $code, want $want; pattern '$pattern')"
    printf '%s\n' "$out" | sed 's/^/    /' | head -8
    FAILURES=$((FAILURES + 1))
  fi
}

case_ "clean setup passes" 0 "^0 FAIL, 0 WARN$" "pass"
case_ "no [tool.mutmut]" 1 "no \[tool.mutmut\] table" "sub('pyproject.toml', '[tool.mutmut]', '[tool.other]')"
case_ "deprecated paths_to_mutate" 1 "paths_to_mutate is deprecated" \
  "sub('pyproject.toml', 'source_paths = [\"src/kilnworks\"]', 'source_paths = [\"src/kilnworks\"]\npaths_to_mutate = \"src/kilnworks/domain/\"')"
case_ "deprecated tests_dir" 1 "tests_dir is deprecated" "sub('pyproject.toml', '[tool.mutmut]', '[tool.mutmut]\ntests_dir = \"tests/unit/\"')"
case_ "runner key is ignored by mutmut 3" 1 "runner is not a mutmut 3.8.1 setting" "sub('pyproject.toml', '[tool.mutmut]', '[tool.mutmut]\nrunner = \"python -m pytest -x\"')"
case_ "backup key is ignored by mutmut 3" 1 "backup is not a mutmut 3.8.1 setting" "sub('pyproject.toml', '[tool.mutmut]', '[tool.mutmut]\nbackup = false')"
case_ "no source_paths" 1 "has no source_paths" "sub('pyproject.toml', 'source_paths = [\"src/kilnworks\"]\n', '')"
case_ "domain only leaves product code out" 1 "src/kilnworks/service_layer/booking.py: is outside source_paths without an approved exclusion" \
  "sub('pyproject.toml', '[\"src/kilnworks\"]', '[\"src/kilnworks/domain\"]'); put('src/kilnworks/service_layer/booking.py', 'def book() -> int:\n    return 1\n')"
case_ "source path under tests/" 1 "is test code" "sub('pyproject.toml', '[\"src/kilnworks\"]', '[\"src/kilnworks\", \"tests\"]')"
case_ "missing --no-cov" 1 "lacks --no-cov" "sub('pyproject.toml', 'pytest_add_cli_args = [\"--no-cov\"]\n', '')"
case_ "coverage flags in addopts" 1 "coverage flags in pytest addopts" "sub('pyproject.toml', 'strict = true', 'strict = true\naddopts = \"--cov=kilnworks --cov-fail-under=100\"')"
case_ "mutate_only_covered_lines" 1 "mutate_only_covered_lines = true" "sub('pyproject.toml', '[tool.mutmut]', '[tool.mutmut]\nmutate_only_covered_lines = true')"
case_ "pragma without approval" 1 "src/kilnworks/domain/firing.py:2: not mutated .* lines [0-9a-f]{12} \| pending" \
  "sub('src/kilnworks/domain/firing.py', 'return a + 1', 'return a + 1  # pragma: no mutate')"
case_ "pragma block form without approval" 1 "firing.py:1: not mutated" \
  "sub('src/kilnworks/domain/firing.py', 'def next_slot(a: int) -> int:', 'def next_slot(a: int) -> int:  # pragma: no mutate block')"
case_ "pragma with an approved lines entry" 0 "^0 FAIL" \
  "import hashlib; sub('src/kilnworks/domain/firing.py', 'return a + 1', 'return a + 1  # pragma: no mutate'); put('mutation/exclusions.txt', 'src/kilnworks/domain/firing.py | lines ' + hashlib.sha256(b'return a + 1  # pragma: no mutate').hexdigest()[:12] + ' | approved 2026-11-20 | kiln controller rounds this itself\n')"
case_ "do_not_mutate on hand-written code" 1 "firing.py: is matched by do_not_mutate without an approved exclusion" \
  "sub('pyproject.toml', 'kiln_api.py\"]', 'kiln_api.py\", \"src/kilnworks/domain/*\"]')"
case_ "do_not_mutate with a pending exclusion" 1 "before the product owner approved it" \
  "sub('pyproject.toml', 'kiln_api.py\"]', 'kiln_api.py\", \"src/kilnworks/domain/*\"]'); put('mutation/exclusions.txt', 'src/kilnworks/domain/ | folder | pending | frozen while the kiln vendor rewrites it\n')"
case_ "do_not_mutate with an approved exclusion" 0 "^0 FAIL" \
  "sub('pyproject.toml', 'kiln_api.py\"]', 'kiln_api.py\", \"src/kilnworks/domain/*\"]'); put('mutation/exclusions.txt', 'src/kilnworks/domain/ | folder | approved 2026-11-20 | frozen while the kiln vendor rewrites it\n')"
case_ "only_mutate leaving a file out" 1 "is not matched by only_mutate" \
  "sub('pyproject.toml', '[tool.mutmut]', '[tool.mutmut]\nonly_mutate = [\"src/kilnworks/adapters/*\"]')"
case_ "do_not_mutate_patterns needs approval" 1 "firing.py:2: not mutated" \
  "sub('pyproject.toml', '[tool.mutmut]', '[tool.mutmut]\ndo_not_mutate_patterns = [\"a \\\\\\\\+ 1\"]')"
case_ "unpinned mutmut" 1 "is not an exact pin" "sub('pyproject.toml', 'mutmut==3.8.1', 'mutmut>=3')"
