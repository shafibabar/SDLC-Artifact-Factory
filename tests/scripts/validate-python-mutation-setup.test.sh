case_ "mutmut run called directly" 1 "mutmut run called directly" "sub('Makefile', 'uv run --frozen bash scripts/run-python-mutation.sh --mutmut-version \$(MUTMUT_VERSION) .', 'uv run mutmut run')"
case_ "export-cicd-stats as a gate" 1 "badge and CI stats are not the verdict" "sub('.github/workflows/mutation.yml', 'run: make install', 'run: uv run mutmut export-cicd-stats')"
case_ "a percentage gate" 1 "a percentage on a mutation line" "sub('Makefile', 'MUTMUT_VERSION := 3.8.1', 'MUTMUT_VERSION := 3.8.1\nMUTATION_THRESHOLD := 60% # mutation floor')"
case_ "masked exit" 1 "the exit status is masked" "sub('.github/workflows/mutation.yml', 'run: make mutation\n', 'run: make mutation || true\n')"
