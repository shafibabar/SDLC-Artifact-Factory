#!/bin/bash
# Synthetic-input test for go-unit-test's check-go-line-coverage.sh.
# Needs no Go toolchain: profiles are written by hand and `go` is a stub.
set -uo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
S="$SCRIPT_DIR/../../skills/go-unit-test/scripts/check-go-line-coverage.sh"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
FAILED=0

# expect <name> <exit-code> <output-regex> <args...>
expect() {
  local name="$1" code="$2" pattern="$3"; shift 3
  local out rc
  out="$(bash "$S" "$@" 2>&1)"; rc=$?
  if [ "$rc" -eq "$code" ] && grep -qE -- "$pattern" <<<"$out"; then
    echo "PASS: $name"
  else
    echo "FAIL: $name (exit $rc, want $code /$pattern/)"; echo "$out"; FAILED=1
  fi
}

M="$TMP/mod"; mkdir -p "$M/a" "$M/gen"
printf 'module example.test/m\n\ngo 1.27\n' > "$M/go.mod"
printf 'package a\n' > "$M/a/a.go"
printf 'package a\n' > "$M/a/x_moq.go"
printf '// Code generated by tool. DO NOT EDIT.\n\npackage gen\n' > "$M/gen/api.go"
printf 'package gen\n\n// Code generated by hand. DO NOT EDIT.\n' > "$M/gen/late.go"
P=example.test/m
prof() { local f="$TMP/$1"; shift; printf '%s\n' "mode: atomic" "$@" > "$f"; echo "$f"; }

ok="$(prof ok "$P/a/a.go:3.1,4.2 2 0" "$P/a/a.go:3.1,4.2 2 5" "$P/a/x_moq.go:3.1,4.2 9 0" "$P/gen/api.go:3.1,4.2 9 0")"
expect "repeated blocks are summed; generated left out" 0 "Statement coverage: 2/2" --profile "$ok" "$M"
expect "excluded files are named" 0 "excluded a/x_moq.go: generated mock" --profile "$ok" "$M"
tiny="$(prof tiny "$P/a/a.go:3.1,4.2 2502 1" "$P/a/a.go:5.1,6.2 1 0")"
expect "one block in 2503 fails" 1 "2502/2503.*" --profile "$tiny" "$M"
expect "above 90 is waivable after review" 1 "may waive" --profile "$tiny" "$M"
expect "exactly 90 has no waiver" 1 "no waiver" --profile "$(prof n90 "$P/a/a.go:3.1,4.2 9 1" "$P/a/a.go:5.1,6.2 1 0")" "$M"
expect "zero-statement block that never ran fails" 1 "1 block\(s\) not run" --profile "$(prof z "$P/a/a.go:3.1,4.2 2 1" "$P/a/a.go:5.1,6.2 0 0")" "$M"
expect "marker after package clause is not generated" 1 "gen/late.go:3.1" --profile "$(prof late "$P/gen/late.go:3.1,4.2 1 0")" "$M"
gap="$(prof gap "$P/a/a.go:3.1,4.2 1 0" "$P/gen/late.go:3.1,4.2 1 1")"
printf 'a/a.go | approved 2026-01-02 | boot code\n' > "$TMP/excl"
expect "approved exclusion applies" 0 "excluded a/a.go: approved: boot code" --profile "$gap" --exclusions "$TMP/excl" "$M"
printf 'a/a.go | pending | boot code\n' > "$TMP/pending"
expect "pending exclusion refused" 2 "not approved" --profile "$gap" --exclusions "$TMP/pending" "$M"
printf 'a/a.go | approved 2026-13-40 | boot code\n' > "$TMP/baddate"
expect "bad date refused" 2 "not approved" --profile "$gap" --exclusions "$TMP/baddate" "$M"
printf 'a/a.go | approved 2026-01-02 | \n' > "$TMP/noreason"
expect "reason required" 2 "NO RESULT" --profile "$gap" --exclusions "$TMP/noreason" "$M"
: > "$TMP/empty"
expect "empty profile is no result" 2 "empty profile" --profile "$TMP/empty" "$M"
expect "missing profile is no result" 2 "cannot read profile" --profile "$TMP/none" "$M"
expect "header only is no result" 2 "no statements" --profile "$(prof head)" "$M"
expect "malformed line is no result" 2 "malformed" --profile "$(prof bad "nonsense")" "$M"
expect "stale profile is no result" 2 "stale profile" --profile "$(prof stale "$P/a/gone.go:1.1,2.2 1 1")" "$M"
expect "other module is no result" 2 "outside module" --profile "$(prof other "x.test/y.go:1.1,2.2 1 1")" "$M"
expect "no go.mod" 2 "no go.mod" "$TMP"
expect "pass-through flags refused" 2 "unknown argument" -run "$M"

# Live mode with a stub go on PATH.
mkdir -p "$TMP/bin"
cat > "$TMP/bin/go" <<'STUB'
#!/bin/bash
echo "$*" >> "$STUB_LOG"
if [ "$1" = list ]; then printf '%s' "${STUB_IGNORED:-}"; exit 0; fi
for a in "$@"; do case "$a" in -coverprofile=*) printf 'mode: atomic\nexample.test/m/a/a.go:3.1,4.2 1 1\n' > "${a#-coverprofile=}";; esac; done
exit "${STUB_TEST_EXIT:-0}"
STUB
chmod +x "$TMP/bin/go"
export STUB_LOG="$TMP/log" PATH="$TMP/bin:$PATH"
expect "live run passes" 0 "PASS: every statement block ran" "$M"
if grep -q -- "-race -covermode=atomic -coverpkg=./... " "$TMP/log" && grep -q -- "-count=1" "$TMP/log"; then
  echo "PASS: full-suite flags used"; else echo "FAIL: flags"; cat "$TMP/log"; FAILED=1; fi
expect "--out keeps the profile" 0 "PASS" --out "$TMP/kept.out" "$M"
if grep -q '^mode: atomic' "$TMP/kept.out"; then echo "PASS: profile copy written"; else echo "FAIL: profile copy"; FAILED=1; fi
expect "--out with --profile refused" 2 "cannot be used" --profile "$ok" --out "$TMP/x.out" "$M"
STUB_TEST_EXIT=1 expect "failed tests give no result" 2 "go test failed" "$M"
STUB_IGNORED="$M/a/a.go
" expect "constrained-out production file is no result" 2 "unmeasured: a/a.go" "$M"
printf '//go:build ignore\n\npackage main\n' > "$M/a/tool.go"
STUB_IGNORED="$M/a/tool.go
$M/a/a_test.go
" expect "ignore tool and test files do not block" 0 "PASS" "$M"
exit $FAILED
