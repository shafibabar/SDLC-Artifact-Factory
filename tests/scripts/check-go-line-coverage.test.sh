#!/bin/bash
# Synthetic-input test for go-unit-test's check-go-line-coverage.sh.
# Needs no Go toolchain: profiles are written by hand and `go` is a stub.
set -uo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
S="$SCRIPT_DIR/../../skills/go-unit-test/scripts/check-go-line-coverage.sh"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
FAILED=0

# expect <name> <exit-code> <output-regex> <args...>
expect() {
  local name="$1" code="$2" pattern="$3"; shift 3
  local out rc
  out="$(bash "$S" "$@" 2>&1)"; rc=$?
  if [ "$rc" -eq "$code" ] && grep -qE -- "$pattern" <<<"$out"; then
    echo "PASS: $name"
  else
    echo "FAIL: $name (exit $rc, want $code /$pattern/)"; echo "$out"; FAILED=1
  fi
}

M="$TMP/mod"; mkdir -p "$M/a" "$M/gen"
printf 'module example.test/m\n\ngo 1.27\n' > "$M/go.mod"
printf 'package a\n' > "$M/a/a.go"
printf 'package a\n' > "$M/a/x_moq.go"
printf '// Code generated by tool. DO NOT EDIT.\n\npackage gen\n' > "$M/gen/api.go"
printf 'package gen\n\n// Code generated by hand. DO NOT EDIT.\n' > "$M/gen/late.go"
P=example.test/m
prof() { local f="$TMP/$1"; shift; printf '%s\n' "mode: atomic" "$@" > "$f"; echo "$f"; }
mkdir -p "$TMP/bin"
cat > "$TMP/bin/go" <<'STUB'
#!/bin/bash
echo "$*" >> "$STUB_LOG"
if [ "$1" = list ]; then printf '%s\n' "$STUB_BUILT"; exit 0; fi
for a in "$@"; do case "$a" in -coverprofile=*) [ -f "$STUB_PROFILE" ] && cp "$STUB_PROFILE" "${a#-coverprofile=}";; esac; done
exit "${STUB_TEST_EXIT:-0}"
STUB
chmod +x "$TMP/bin/go"
R="$(cd "$M" && pwd -P)"
export STUB_LOG="$TMP/log" PATH="$TMP/bin:$PATH" STUB_BUILT="$R/a/a.go
$R/a/x_moq.go
$R/gen/api.go
$R/gen/late.go"

ok="$(prof ok "$P/a/a.go:3.1,4.2 2 0" "$P/a/a.go:3.1,4.2 2 5" "$P/a/x_moq.go:3.1,4.2 9 0" "$P/gen/api.go:3.1,4.2 9 0")"
STUB_PROFILE="$ok" expect "repeated blocks are summed; generated left out" 0 "Statement coverage: 2/2" "$M"
STUB_PROFILE="$ok" expect "excluded files are named" 0 "excluded a/x_moq.go: generated mock" "$M"
tiny="$(prof tiny "$P/a/a.go:3.1,4.2 2502 1" "$P/a/a.go:5.1,6.2 1 0")"
STUB_PROFILE="$tiny" expect "one block in 2503 fails" 1 "2502/2503.*" "$M"
STUB_PROFILE="$tiny" expect "above 90 is waivable after review" 1 "may waive" "$M"
STUB_PROFILE="$(prof n90 "$P/a/a.go:3.1,4.2 9 1" "$P/a/a.go:5.1,6.2 1 0")" expect "exactly 90 has no waiver" 1 "no waiver" "$M"
STUB_PROFILE="$(prof z "$P/a/a.go:3.1,4.2 2 1" "$P/a/a.go:5.1,6.2 0 0")" expect "zero-statement block that never ran fails" 1 "1 block\(s\) not run" "$M"
STUB_PROFILE="$(prof late "$P/gen/late.go:3.1,4.2 1 0")" expect "marker after package clause is not generated" 1 "gen/late.go:3.1" "$M"
gap="$(prof gap "$P/a/a.go:3.1,4.2 1 0" "$P/gen/late.go:3.1,4.2 1 1")"
printf 'a/a.go | approved 2026-01-02 | boot code\n' > "$TMP/excl"
STUB_PROFILE="$gap" expect "approved exclusion applies" 0 "excluded a/a.go: approved: boot code" --exclusions "$TMP/excl" "$M"
printf 'a/a.go | pending | boot code\n' > "$TMP/pending"
STUB_PROFILE="$gap" expect "pending exclusion refused" 2 "not approved" --exclusions "$TMP/pending" "$M"
printf 'a/a.go | approved 2026-13-40 | boot code\n' > "$TMP/baddate"
STUB_PROFILE="$gap" expect "bad date refused" 2 "not approved" --exclusions "$TMP/baddate" "$M"
printf 'a/a.go | approved 2026-01-02 | \n' > "$TMP/noreason"
STUB_PROFILE="$gap" expect "reason required" 2 "NO RESULT" --exclusions "$TMP/noreason" "$M"
: > "$TMP/empty"
STUB_PROFILE="$TMP/empty" expect "empty profile is no result" 2 "empty profile" "$M"
STUB_PROFILE="$TMP/none" expect "missing profile is no result" 2 "cannot read profile" "$M"
STUB_PROFILE="$(prof head)" expect "header only is no result" 2 "no statements" "$M"
STUB_PROFILE="$(prof bad "nonsense")" expect "malformed line is no result" 2 "malformed" "$M"
STUB_PROFILE="$(prof stale "$P/a/gone.go:1.1,2.2 1 1")" expect "stale profile is no result" 2 "stale profile" "$M"
STUB_PROFILE="$(prof other "x.test/y.go:1.1,2.2 1 1")" expect "other module is no result" 2 "outside module" "$M"
expect "no go.mod" 2 "no go.mod" "$TMP"
expect "pass-through flags refused" 2 "unknown argument" -run "$M"

export STUB_PROFILE="$ok"
expect "pass-through flags refused" 2 "unknown argument" -run "$M"
expect "--profile is not accepted" 2 "unknown argument" --profile "$ok" "$M"
: > "$TMP/log"
expect "live run passes" 0 "PASS: every measured statement block ran" "$M"
if grep -q -- "-race -covermode=atomic -coverpkg=./... " "$TMP/log" && grep -q -- "-count=1" "$TMP/log"; then
  echo "PASS: full-suite flags used"; else echo "FAIL: flags"; cat "$TMP/log"; FAILED=1; fi
expect "--out keeps the profile" 0 "PASS" --out "$TMP/kept.out" "$M"
if grep -q '^mode: atomic' "$TMP/kept.out"; then echo "PASS: profile copy written"; else echo "FAIL: profile copy"; FAILED=1; fi
STUB_TEST_EXIT=1 expect "failed tests give no result and block" 2 "blocks the build" "$M"
mkdir -p "$M/only"; printf '//go:build extra\n\npackage only\n' > "$M/only/b.go"
expect "folder invisible to go list is no result" 2 "unmeasured: only/b.go" "$M"
printf 'only/b.go | approved 2026-01-02 | other build\n' > "$TMP/only"
expect "approved exception passes and is named as not measured" 0 "NOT measured, by approved exception: only/b.go" --exclusions "$TMP/only" "$M"
rm -r "$M/only"
printf '//go:build ignore\n\npackage main\n' > "$M/a/tool.go"
printf 'package a\n' > "$M/a/a_test.go"
mkdir -p "$M/vendor/v" "$M/testdata" "$M/_x"; for f in vendor/v/v.go testdata/t.go _x/x.go; do printf 'package v\n' > "$M/$f"; done
expect "ignore tool, test, vendor and testdata files do not block" 0 "PASS" "$M"
# test support: internal/test/ is an approved class; shipped code may not use it
mkdir -p "$M/internal/test/db" "$M/internal/testing" "$M/cmd/s"
printf 'package test\n' > "$M/internal/test/h.go"; printf '//go:build extra\n\npackage db\n' > "$M/internal/test/db/tx.go"
printf 'package a\n\nimport "example.test/m/internal/test"\n' > "$M/a/a_test.go"
sup="$(prof sup "$P/a/a.go:3.1,4.2 2 1" "$P/internal/test/h.go:3.1,4.2 9 0")"
STUB_PROFILE="$sup" expect "test support is left out with no entry" 0 "Statement coverage: 2/2" "$M"
STUB_PROFILE="$sup" expect "every support file is listed, built or not" 0 "excluded internal/test/db/tx.go: test support" "$M"
printf 'package testing\n' > "$M/internal/testing/t.go"
STUB_BUILT="$STUB_BUILT
$R/internal/testing/t.go" STUB_PROFILE="$(prof near "$P/a/a.go:3.1,4.2 2 1" "$P/internal/testing/t.go:1.1,2.2 1 0")" \
  expect "a similar folder name is not in the class" 1 "internal/testing/t.go:1.1" "$M"
rm -r "$M/internal/testing"
for form in 'import "example.test/m/internal/test"' 'import h "example.test/m/internal/test/db"' \
  $'import (\n\t"fmt"\n\t// note\n\t_ "example.test/m/internal/test/db"\n)' 'import `example.test/m/internal/test`'; do
  printf '//go:build extra\n\n// Package s ships.\npackage main\n\n%s\n' "$form" > "$M/cmd/s/main.go"
  STUB_PROFILE="$sup" expect "shipped import fails: $(tr '\n\t' '  ' <<<"$form")" 1 "cmd/s/main.go: imports example.test/m/internal/test" "$M"
done
printf 'package main\n\n// import "example.test/m/internal/test"\nvar s = `import "example.test/m/internal/test"`\n' > "$M/cmd/s/main.go"
STUB_BUILT="$STUB_BUILT
$R/cmd/s/main.go" STUB_PROFILE="$sup" expect "a comment or string is not an import" 0 "PASS" "$M"
rm -r "$M/cmd"; printf 'package main\n' > "$M/internal/test/run.go"
STUB_PROFILE="$sup" expect "package main in the folder fails" 1 "package main under internal/test" "$M"
exit $FAILED
